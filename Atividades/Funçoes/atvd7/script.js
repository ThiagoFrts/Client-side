// 7. Função de média
// Crie uma função que receba três notas (double) e retorne a média.

function double(a, b, c){
    return (a+b+c)/3
}

let a = Number(window.prompt(`Digite a 1° nota: `))
let b = Number(window.prompt(`Digite a 2° nota: `))
let c = Number(window.prompt(`Digite a 3° nota: `))

let media = double(a, b, c)
alert(`A média é: ${media}`)

















