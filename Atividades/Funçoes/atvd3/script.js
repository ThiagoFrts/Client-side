// 3. Função de subtração
// Crie uma função que receba dois números inteiros e retorne a subtração (a - b).

function sub(a, b) {
    return a - b
}
let a = Number(window.prompt(`Digite um número: `))
let b = Number(window.prompt(`Digite outro número: `))
let resultado = sub(a, b)

alert(`A subtração dos números é: ${resultado}`)


















