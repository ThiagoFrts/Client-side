// Desafio: Crie três quadrados cinza e um botão chamado "Colorir".
// Ao clicar no botão:
// • O primeiro quadrado deve ficar vermelho.
// • O segundo deve ficar verde.
// • O terceiro deve ficar azul.

function colorir() {
    document.getElementsByClassName("qua")[0].style.background = "#850d0d"
    document.getElementsByClassName("qua")[1].style.background = "#186f10"
    document.getElementsByClassName("qua")[2].style.background = "#090d68"
}




