// ✅ 11. Contar até o número digitado com for
// Peça ao usuário para digitar um número inteiro positivo e, usando a estrutura for, exiba todos
// os números de 1 até esse número.


let a = Number(window.prompt(`Digite um número para realizar a \ncontagem regressiva: `))
for(let i = 1; i <= a; i++){
    alert(i)
}
