// ✅ 5. Senha correta com do-while
// Crie um programa que continue pedindo ao usuário para digitar uma senha até que ele digite
// o valor correto (por exemplo, 1234). Quando a senha correta for digitada, exiba &quot;Acesso
// permitido&quot;

let a; 
 do{
    a = Number(window.prompt(`Olá usúario!\nDigite sua senha: `))
 }

 
 while(a!=`1234`);

 alert(`Acesso permitido!`)

     
 

