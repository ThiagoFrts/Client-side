// Peça ao usuário para digitar um número e informe se ele é positivo, negativo
// ou zero.
let a = Number(window.prompt("Digite um número:"))

if(a>=1){

    alert("Seu número é positivo.")
}
else if (a==0){
    alert("Seu número é zero.")
}

else{
    alert("Seu número é negativo.")
}